KEEP_PREFIXES = ("dest.", "source.", "download.", "trust.", "adapter.", "restore.renamed-suffix")

root = os.path.join(os.path.dirname(__file__), "..", "src", "WindowsReborn.Core", "Localization")
for idx, lang in enumerate(("es", "en")):
    path = os.path.join(root, f"{lang}.json")
    old = json.load(open(path, encoding="utf-8"))
    out = {k: v for k, v in old.items() if k.startswith(KEEP_PREFIXES)}
    for k, pair in S.items():
        out[k] = pair[idx]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(sorted(out.items())), f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(lang, len(out))
